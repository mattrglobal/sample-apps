import assert from "node:assert/strict";
import { test } from "node:test";
import {
	compareVersions,
	diffVersions,
	directAncestors,
	isMajorBump,
	parseNpmLock,
	parseYarnLock,
	pruneYarnLock,
	resolvedDirect,
} from "./lockfile.mjs";

const npmLock = JSON.stringify({
	lockfileVersion: 3,
	packages: {
		"": { name: "app", dependencies: { next: "16.3.8" } },
		"node_modules/next": { version: "16.3.8", dependencies: { "@next/env": "16.3.8" } },
		"node_modules/@next/env": { version: "16.3.8" },
		"node_modules/a/node_modules/qs": { version: "6.13.0" },
		"node_modules/qs": { version: "6.14.0" },
		"node_modules/local": { resolved: "../local", link: true },
	},
});

const yarnLock = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 10
  cacheKey: 10c0

"@expo/cli@npm:55.0.32":
  version: 55.0.32
  resolution: "@expo/cli@npm:55.0.32"
  languageName: node
  linkType: hard

"expo@npm:^55":
  version: 55.0.10
  resolution: "expo@npm:55.0.10"
  dependencies:
    "@expo/cli": "npm:55.0.32"
  languageName: node
  linkType: hard

"glob@npm:^10.5.0, glob@npm:^10.2.2":
  version: 10.5.0
  resolution: "glob@npm:10.5.0"
  languageName: node
  linkType: hard

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown
  linkType: soft
`;

test("parseNpmLock collects every installed copy and skips links and the root", () => {
	const v = parseNpmLock(npmLock);
	assert.deepEqual([...v.get("qs")].sort(), ["6.13.0", "6.14.0"]);
	assert.deepEqual([...v.get("@next/env")], ["16.3.8"]);
	assert.equal(v.has("local"), false);
	assert.equal(v.has(""), false);
});

test("parseYarnLock reads scoped and multi-descriptor entries and skips the workspace", () => {
	const v = parseYarnLock(yarnLock);
	assert.deepEqual([...v.get("@expo/cli")], ["55.0.32"]);
	assert.deepEqual([...v.get("glob")], ["10.5.0"]);
	assert.equal(v.has("app"), false);
	assert.equal(v.has("__metadata"), false);
});

test("resolvedDirect matches the exact package.json range", () => {
	assert.equal(resolvedDirect("npm", npmLock, "next", "16.3.8"), "16.3.8");
	assert.equal(resolvedDirect("yarn", yarnLock, "expo", "^55"), "55.0.10");
	assert.equal(resolvedDirect("yarn", yarnLock, "glob", "^10.2.2"), "10.5.0");
	assert.equal(resolvedDirect("yarn", yarnLock, "glob", "^9"), undefined);
});

test("pruneYarnLock keeps the header, metadata and held packages only", () => {
	const pruned = pruneYarnLock(yarnLock, new Set(["@expo/cli"]));
	assert.match(pruned, /^# This file is generated/);
	assert.match(pruned, /__metadata:\n {2}version: 10/);
	assert.match(pruned, /"@expo\/cli@npm:55.0.32":/);
	assert.doesNotMatch(pruned, /expo@npm:\^55|glob@npm|workspace/);
	assert.deepEqual([...parseYarnLock(pruned).keys()], ["@expo/cli"]);
});

test("diffVersions reports changed, added and removed packages", () => {
	const before = new Map([["a", new Set(["1.0.0"])], ["b", new Set(["2.0.0"])]]);
	const after = new Map([["a", new Set(["1.1.0"])], ["c", new Set(["3.0.0"])]]);
	assert.deepEqual(diffVersions(before, after), [
		{ name: "a", from: ["1.0.0"], to: ["1.1.0"] },
		{ name: "b", from: ["2.0.0"], to: [] },
		{ name: "c", from: [], to: ["3.0.0"] },
	]);
});

test("version helpers", () => {
	assert.ok(compareVersions("10.0.0", "9.9.9") > 0);
	assert.ok(compareVersions("1.2.3", "1.2.10") < 0);
	assert.equal(isMajorBump("9.0.2", "10.0.0"), true);
	assert.equal(isMajorBump("0.3.1", "0.4.0"), true);
	assert.equal(isMajorBump("16.1.5", "16.3.8"), false);
});

test("directAncestors walks the dependency graph up to direct dependencies", () => {
	assert.deepEqual(directAncestors("npm", npmLock, "@next/env", new Set(["next"])), ["next"]);
	assert.deepEqual(directAncestors("yarn", yarnLock, "@expo/cli", new Set(["expo", "glob"])), ["expo"]);
	assert.deepEqual(directAncestors("yarn", yarnLock, "glob", new Set(["expo"])), []);
});
